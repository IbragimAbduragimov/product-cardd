def subtitle_events():
    """Привязывает фрагменты субтитров к пословным таймкодам распознавания."""
    words = json.load(open(f"{ROOT}/build/master_words.json"))
    total = sum(n for _, n in SUBS)
    assert total == len(words), f"субтитры покрывают {total} слов, распознано {len(words)}"
    events, i = [], 0
    for text, n in SUBS:
        chunk = words[i:i + n]
        events.append(dict(text=text, s=chunk[0]["s"] - 0.06, e=chunk[-1]["e"] + 0.30,
                           asr=" ".join(w["w"] for w in chunk)))
        i += n
    for a, b in zip(events, events[1:]):
        if a["e"] > b["s"] - 0.02 or b["s"] - a["e"] < 0.25:
            a["e"] = b["s"] - 0.02          # без «мигания» на коротких паузах
    events[-1]["e"] = min(events[-1]["e"] + 0.4, MAIN_END)
    return events


def plain(text):
    return re.sub(r"\*", "", text)


